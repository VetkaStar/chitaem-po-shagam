export function wordEntry(word: string) {
  return wordBank.find((e) => e.word === word);
}
export function wordParts(word: string): readonly string[] {
  return wordEntry(word)?.parts || [word];
}
export function freshWordDeck(
  pool: string[],
  length: number,
  recent: string[],
  random = Math.random,
) {
  const unique = [...new Set(pool)],
    seen = new Set(recent),
    fresh = unique.filter((w) => !seen.has(w));
  const old = unique
    .filter((w) => seen.has(w))
    .sort((a, b) => recent.lastIndexOf(a) - recent.lastIndexOf(b));
  for (let i = fresh.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [fresh[i], fresh[j]] = [fresh[j], fresh[i]];
  }
  // Once every word has been seen, mix groups from oldest to newest.
  // This avoids replaying the previous cycle in exactly the same order.
  if (!fresh.length) {
    const width = Math.max(2, Math.ceil(old.length / 3));
    for (let start = 0; start < old.length; start += width) {
      for (let i = Math.min(start + width, old.length) - 1; i > start; i--) {
        const j = start + Math.floor(random() * (i - start + 1));
        [old[i], old[j]] = [old[j], old[i]];
      }
    }
  }
  const result = [...fresh, ...old];
  if (result.length > 1 && result[0] === recent.at(-1))
    [result[0], result[1]] = [result[1], result[0]];
  while (result.length < length && unique.length) {
    let batch = [...unique];
    for (let i = batch.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [batch[i], batch[j]] = [batch[j], batch[i]];
    }
    if (batch.length > 1 && batch[0] === result.at(-1))
      [batch[0], batch[1]] = [batch[1], batch[0]];
    result.push(...batch);
  }
  return result.slice(0, length);
}
