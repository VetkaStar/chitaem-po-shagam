export function normalize(v: string) {
  return v
    .toLocaleUpperCase('ru')
    .replace(/Ё/g, 'Е')
    .replace(/[^А-Я]/g, '');
}
export function checkTyped(
  v: string,
  target: string,
  alternatives: string[] = [],
) {
  return (
    [target, ...alternatives].some((t) => normalize(v) === normalize(t)) &&
    normalize(v).length > 0
  );
}
