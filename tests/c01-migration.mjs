class Store {
  state = null; backups = []; fail = false;
  async read() { return structuredClone(this.state); }
  async commit(next, revision, backup = false) {
    validateStoredSnapshot(next,supply);
    if (this.fail) throw Error('QUOTA_TEST');
    assert.equal(this.state?.storageRevision ?? null,revision);
    if (backup) this.backups.push(structuredClone(this.state));
    this.state = structuredClone({...next,storageRevision:(revision ?? -1)+1});
    return this.read();
  }
}
