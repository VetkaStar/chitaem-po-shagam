"""Prepare the nine approved PNGs with the existing Pillow/WebP workflow.

No generation, crop, repaint, or source modification. Run from any directory.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.local/program-pilot-plan-20261104/generated'
DEST = ROOT / 'public/illustrations/pilot-v1'
variants = ('main', 'alternate', 'context')
words = {
    'lamp': ('лампа', [
        'Настольная лампа с зелёным абажуром, изогнутой ножкой и круглым основанием.',
        'Та же настольная лампа с зелёным абажуром, вид сбоку.',
        'Настольная лампа с зелёным абажуром освещает открытую книгу на столе.',
    ]),
    'grain': ('крупа', [
        'Прозрачный пакет с сухой крупой; рядом лежат отдельные зёрна.',
        'Сухая крупа в стеклянной банке и деревянном совке.',
        'Пакет сухой крупы и ложка на кухонном столе.',
    ]),
}
stories = {
    'catfish': ('Сом', 'У нас сом. У сома усы.',
        'Мама и ребёнок у домашнего аквариума; у сома хорошо видны длинные усы.'),
    'sled': ('Сани', 'У Иры сани. Ира катит сани.',
        'Ира стоит позади пустых саней и двигает их вперёд обеими руками; верёвка лежит на сиденье.'),
    'bag': ('Сумка', 'У мамы сумка. Там крупа.',
        'Мама держит открытую сумку; внутри виден пакет сухой крупы.'),
}

def digest(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()

jobs = [(f'{name}-{variant}', f'{name}-{variant}.png', (320, 640), (1254, 1254))
        for name in words for variant in variants]
jobs += [(f'story-{name}', f'story-{name}' + ('-v2' if name == 'sled' else '') + '.png',
          (560, 320, 1120), (1672, 941)) for name in stories]
sources, images, srcsets = [], [], {}
for stem, filename, widths, expected in jobs:
    file = SOURCE / filename
    with Image.open(file) as im:
        assert im.format == 'PNG' and im.size == expected, filename
        im.verify()
    sources.append(dict(path=file.relative_to(ROOT).as_posix(), sha256=digest(file)))

DEST.mkdir(parents=True, exist_ok=True)
for (stem, filename, widths, expected), source in zip(jobs, sources):
    entries = []
    with Image.open(SOURCE / filename) as original:
        im = original.convert('RGB')
        for width in widths:
            height = round(im.height * width / im.width)
            name = stem + ('' if width == widths[0] else f'-{width}w') + '.webp'
            output = DEST / name
            im.resize((width, height), Image.Resampling.LANCZOS).save(output, 'WEBP', quality=78, method=6)
            with Image.open(output) as check:
                assert check.format == 'WEBP' and check.size == (width, height)
                check.verify()
            src = output.relative_to(ROOT / 'public').as_posix()
            images.append(dict(src=src, width=width, height=height, bytes=output.stat().st_size,
                               sha256=digest(output), source=source['path']))
            entries.append((width, f'{src} {width}w'))
    assert digest(SOURCE / filename) == source['sha256']
    srcsets[f'illustrations/pilot-v1/{stem}.webp'] = ', '.join(entry for _, entry in sorted(entries))

catalog, word_map, text_map, story_frames = {}, {}, {}, {}
for name, (target, alts) in words.items():
    asset_id = f'word-pilot-{name}-v1'
    catalog[asset_id] = dict(target=target, variants={variant: dict(
        src=f'illustrations/pilot-v1/{name}-{variant}.webp', alt=alt, width=320, height=320)
        for variant, alt in zip(variants, alts)})
    word_map[target.upper()] = asset_id
for name, (title, text, alt) in stories.items():
    asset_id = f'scene-pilot-{name}-v1'
    frame = dict(src=f'illustrations/pilot-v1/story-{name}.webp', alt=alt,
                 width=560, height=round(941 * 560 / 1672))
    # Existing gallery contract has three named variants. A single approved
    # scene intentionally uses one source; the gallery suppresses duplicate UI.
    catalog[asset_id] = dict(target=title, variants={variant: frame for variant in variants})
    text_map[f'pilot-story-{name}-v1'] = asset_id
    story_frames[asset_id] = [frame]

def export(name, value, annotation=''):
    return f'export const {name}{annotation} = ' + json.dumps(value, ensure_ascii=False, indent=2) + ';\n'

(ROOT / 'content/illustrations-pilot.ts').write_text(
    '// Generated by tests/prepare-pilot-illustrations.py from approved local PNGs.\n'
    + export('pilotIllustrations', catalog)
    + export('pilotWordIllustrations', word_map, ': Record<string, keyof typeof pilotIllustrations>')
    + export('pilotTextIllustrations', text_map, ': Record<string, keyof typeof pilotIllustrations>')
    + export('pilotStoryFrames', story_frames), encoding='utf-8')
(ROOT / 'content/illustrations-pilot-sources.ts').write_text(
    export('pilotIllustrationSources', srcsets, ': Record<string, string>'), encoding='utf-8')
(ROOT / 'docs/PILOT-ILLUSTRATIONS-IMPORT.json').write_text(json.dumps(dict(
    workflow='Pillow LANCZOS, RGB, WebP quality=78 method=6; no crop',
    sources=sources, images=images, sourceHashesUnchanged=True), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'{len(sources)} unchanged PNGs; {len(images)} verified WebP files; {sum(i["bytes"] for i in images)} bytes')
